def add(a, b):
    """加法函数"""
    return a + b

def subtract(a, b):
    """减法函数"""
    return a - b

def multiply(a, b):
    """乘法函数"""
    return a * b

def greet(name):
    """问候函数"""
    return f"Hello, {name}!"

def sum_list(numbers):
    """计算列表总和"""
    return sum(numbers)

def create_dict():
    """创建字典"""
    return {"name": "Python", "version": 3.10, "active": True}
